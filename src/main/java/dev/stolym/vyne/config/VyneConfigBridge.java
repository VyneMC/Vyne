package dev.stolym.vyne.config;

import dev.stolym.vyne.util.VyneLogger;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.concurrent.ConcurrentHashMap;

public final class VyneConfigBridge {
    private record ConfigEntry(String modId, Object type, Object spec, String fileName) {}

    private static final Map<String, List<ConfigEntry>> configs = new ConcurrentHashMap<>();

    public static void register(String modId, Object type, Object spec, String fileName) {
        configs.computeIfAbsent(modId, k -> new ArrayList<>())
               .add(new ConfigEntry(modId, type, spec, fileName));
        VyneLogger.info("[Config] Registered config for '" + modId + "': " + fileName + " (type: " + type + ")");
        tryWrite(modId, type, spec, fileName);
    }

    private static void tryWrite(String modId, Object type, Object spec, String fileName) {
        try {
            Path configDir = net.neoforged.fml.loading.FMLPaths.CONFIGDIR.get();
            Files.createDirectories(configDir);
            Path file = configDir.resolve(fileName);

            if (spec instanceof net.neoforged.neoforge.common.ModConfigSpec mcSpec) {
                if (!Files.exists(file)) {
                    Files.writeString(file, buildToml(mcSpec, null));
                    VyneLogger.info("[Config] Wrote default config: " + file);
                }
                loadIntoSpec(file, mcSpec, modId);
                return;
            }

            if (!Files.exists(file)) {
                String content = generateToml(modId, spec);
                Files.writeString(file, content);
                VyneLogger.info("[Config] Wrote default config: " + file);
            }
        } catch (Exception e) {
            VyneLogger.warn("[Config] Could not write config for " + modId + ": " + e.getMessage());
        }
    }

    private static void loadIntoSpec(Path file, net.neoforged.neoforge.common.ModConfigSpec spec, String modId) {
        try {
            Map<String, Object> values = new java.util.HashMap<>();
            com.moandjiezana.toml.Toml toml = new com.moandjiezana.toml.Toml().read(file.toFile());
            for (net.neoforged.neoforge.common.ModConfigSpec.Entry e : spec.getEntries().values()) {
                Object v = lookup(toml, e.path);
                if (v != null) values.put(e.key(), v);
            }
            spec.acceptLoadedValues(values, () -> {
                try {
                    Files.writeString(file, buildToml(spec, null));
                } catch (Exception ex) {
                    VyneLogger.warn("[Config] Could not save config " + file.getFileName() + ": " + ex.getMessage());
                }
            });
            VyneLogger.info("[Config] Loaded " + values.size() + "/" + spec.getEntries().size()
                    + " entries for '" + modId + "' from " + file.getFileName());
        } catch (Exception e) {
            VyneLogger.warn("[Config] Failed to load config " + file + ": " + e.getMessage());
        }
    }

    private static Object lookup(com.moandjiezana.toml.Toml toml, List<String> path) {
        Map<String, Object> cursor = toml.toMap();
        for (int i = 0; i < path.size() - 1; i++) {
            Object next = cursor.get(path.get(i));
            if (!(next instanceof Map)) return null;
            @SuppressWarnings("unchecked")
            Map<String, Object> nextMap = (Map<String, Object>) next;
            cursor = nextMap;
        }
        return cursor.get(path.get(path.size() - 1));
    }

    private static String buildToml(net.neoforged.neoforge.common.ModConfigSpec spec, String modId) {
        StringBuilder sb = new StringBuilder();
        if (modId != null) sb.append("# Config for ").append(modId).append(" — generated by Vyne\n\n");

        List<net.neoforged.neoforge.common.ModConfigSpec.Entry> topLevel = new java.util.ArrayList<>();
        Map<String, List<net.neoforged.neoforge.common.ModConfigSpec.Entry>> sections = new java.util.LinkedHashMap<>();
        for (net.neoforged.neoforge.common.ModConfigSpec.Entry e : spec.getEntries().values()) {
            if (e.path.isEmpty()) continue;
            if (e.path.size() == 1) topLevel.add(e);
            else sections.computeIfAbsent(String.join(".", e.path.subList(0, e.path.size() - 1)),
                    k -> new java.util.ArrayList<>()).add(e);
        }

        for (net.neoforged.neoforge.common.ModConfigSpec.Entry e : topLevel) {
            appendEntry(sb, spec, e);
        }
        for (var sec : sections.entrySet()) {
            sb.append("\n[").append(sec.getKey()).append("]\n");
            for (net.neoforged.neoforge.common.ModConfigSpec.Entry e : sec.getValue()) {
                appendEntry(sb, spec, e);
            }
        }
        return sb.toString();
    }

    private static void appendEntry(StringBuilder sb, net.neoforged.neoforge.common.ModConfigSpec spec,
                                    net.neoforged.neoforge.common.ModConfigSpec.Entry e) {
        List<String> path = e.path;
        if (e.comment != null && !e.comment.isBlank()) {
            for (String line : e.comment.split("\n")) sb.append("# ").append(line).append("\n");
        }
        Object v = spec.valueFor(e);
        sb.append(path.get(path.size() - 1)).append(" = ").append(toTomlValue(v)).append("\n");
    }

    private static String generateToml(String modId, Object spec) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Config for ").append(modId).append(" — generated by Vyne\n\n");
        if (spec == null) return sb.toString();
        Class<?> cursor = spec.getClass();
        while (cursor != null && !cursor.equals(Object.class)) {
            for (java.lang.reflect.Field f : cursor.getDeclaredFields()) {
                try {
                    f.setAccessible(true);
                    Object val = f.get(spec);
                    val = unwrapConfigValue(val);
                    sb.append(f.getName()).append(" = ").append(toTomlValue(val)).append("\n");
                } catch (Exception ignored) {}
            }
            cursor = cursor.getSuperclass();
        }
        return sb.toString();
    }

    private static Object unwrapConfigValue(Object val) {
        if (val == null) return null;
        String typeName = val.getClass().getName();
        if (!typeName.contains("ConfigValue") && !typeName.contains("ForgeConfigSpec")) return val;
        try {
            java.lang.reflect.Method get = val.getClass().getMethod("get");
            return get.invoke(val);
        } catch (Throwable ignored) {}
        try {
            java.lang.reflect.Method getDefault = val.getClass().getMethod("getDefault");
            return getDefault.invoke(val);
        } catch (Throwable ignored) {}
        return val;
    }

    private static String toTomlValue(Object val) {
        if (val == null) return "\"\"";
        if (val instanceof String s) return "\"" + s.replace("\"", "\\\"") + "\"";
        if (val instanceof Boolean || val instanceof Number) return val.toString();
        return "\"" + val + "\"";
    }

    public static List<ConfigEntry> getConfigs(String modId) {
        return configs.getOrDefault(modId, Collections.emptyList());
    }

    public static String buildTomlForTests(net.neoforged.neoforge.common.ModConfigSpec spec) {
        return buildToml(spec, null);
    }

    public static void loadIntoSpecForTests(Path file, net.neoforged.neoforge.common.ModConfigSpec spec) {
        loadIntoSpec(file, spec, "test");
    }
}
